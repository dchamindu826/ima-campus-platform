const puppeteer = require('puppeteer-extra');
const StealthPlugin = require('puppeteer-extra-plugin-stealth');
const fs = require('fs');
const path = require('path');

puppeteer.use(StealthPlugin());

const COOKIE_PATH = path.join(__dirname, '../yt_cookies.txt');

function formatCookieToNetscape(cookie) {
    let domain = cookie.domain;
    if (!domain.startsWith('.')) {
        domain = '.' + domain;
    }
    const includeSubDomain = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const cookiePath = cookie.path || '/';
    const secure = cookie.secure ? 'TRUE' : 'FALSE';
    const expiry = cookie.expires === -1 ? Math.floor(Date.now() / 1000) + 31536000 : Math.floor(cookie.expires);
    
    return `${domain}\t${includeSubDomain}\t${cookiePath}\t${secure}\t${expiry}\t${cookie.name}\t${cookie.value}`;
}

async function generateYoutubeCookies() {
    console.log('🍪 Starting YouTube cookie generation...');
    let browser;
    try {
        browser = await puppeteer.launch({
            headless: 'new',
            args: [
                '--no-sandbox',
                '--disable-setuid-sandbox',
                '--disable-blink-features=AutomationControlled',
            ]
        });

        const page = await browser.newPage();
        
        // Randomize user agent slightly
        await page.setUserAgent('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36');

        console.log('Navigating to YouTube...');
        await page.goto('https://www.youtube.com', { waitUntil: 'networkidle2', timeout: 60000 });

        // Handle consent dialog if it appears
        try {
            const acceptButton = await page.$('button[aria-label="Accept all"], button[aria-label="Accept the use of cookies and other data for the purposes described"]');
            if (acceptButton) {
                console.log('Consent dialog found, accepting...');
                await acceptButton.click();
                await new Promise(resolve => setTimeout(resolve, 3000));
            }
        } catch (e) {
            console.log('No consent dialog found or error clicking it:', e.message);
        }

        console.log('Waiting to ensure cookies are populated...');
        await new Promise(resolve => setTimeout(resolve, 5000));

        const cookies = await page.cookies();
        
        if (cookies.length === 0) {
            throw new Error('No cookies found!');
        }

        let netscapeCookies = "# Netscape HTTP Cookie File\n# This file was generated by Puppeteer\n\n";
        cookies.forEach(cookie => {
            netscapeCookies += formatCookieToNetscape(cookie) + '\n';
        });

        fs.writeFileSync(COOKIE_PATH, netscapeCookies, 'utf8');
        console.log(`✅ Successfully generated ${cookies.length} cookies and saved to ${COOKIE_PATH}`);

    } catch (error) {
        console.error('❌ Error generating YouTube cookies:', error.message);
    } finally {
        if (browser) {
            await browser.close();
        }
    }
}

module.exports = { generateYoutubeCookies };

// Run if called directly
if (require.main === module) {
    generateYoutubeCookies();
}
