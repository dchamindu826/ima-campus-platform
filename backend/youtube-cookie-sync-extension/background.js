function formatCookieToNetscape(cookie) {
    let domain = cookie.domain;
    if (!domain.startsWith('.')) {
        domain = '.' + domain;
    }
    const includeSubDomain = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const cookiePath = cookie.path || '/';
    const secure = cookie.secure ? 'TRUE' : 'FALSE';
    const expiry = cookie.expirationDate ? Math.floor(cookie.expirationDate) : Math.floor(Date.now() / 1000) + 31536000;
    
    return `${domain}\t${includeSubDomain}\t${cookiePath}\t${secure}\t${expiry}\t${cookie.name}\t${cookie.value}`;
}

async function syncCookies() {
    chrome.cookies.getAll({}, async (allCookies) => {
        const cookies = allCookies.filter(c => c.domain.includes('youtube.com') || c.domain.includes('google.com'));
        
        if (!cookies || cookies.length === 0) {
            console.log("No YouTube/Google cookies found.");
            return;
        }

        let netscapeCookies = "# Netscape HTTP Cookie File\n# Generated by IMA Cookie Sync Extension\n\n";
        cookies.forEach(cookie => {
            netscapeCookies += formatCookieToNetscape(cookie) + '\n';
        });

        try {
            const response = await fetch("https://imacampus.online/api/mobile/update-yt-cookies", {
                method: "POST",
                headers: {
                    "Content-Type": "application/json"
                },
                body: JSON.stringify({ cookies: netscapeCookies })
            });
            const data = await response.json();
            console.log("Sync Response:", data);
        } catch (error) {
            console.error("Sync Error:", error);
        }
    });
}

// Sync immediately on install/start
syncCookies();

// Sync every 12 hours
chrome.alarms.create("syncCookies", { periodInMinutes: 720 });
chrome.alarms.onAlarm.addListener((alarm) => {
    if (alarm.name === "syncCookies") {
        syncCookies();
    }
});
